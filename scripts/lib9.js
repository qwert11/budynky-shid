function semiHouseQuality9(u) {
  const ppm = bell(u.ppm, 120, 260, 40, 450);
  const area = bell(u.area, 90, 180, 60, 300);
  const land = u.land == null ? 0.5 : bell(u.land, 8, 30, 1, 80);
  const ready = (SEMI[u.semi] || SEMI.unfin).w;
  const near = down(u.km, 0, 12);
  const bonus = (u.noCommission ? 0.02 : 0) + (u.photos && u.photos.length >= 3 ? 0.02 : 0);
  return scale((ppm + area + land + ready) / 6 + near / 3 + bonus);
}
function semiFlatQuality9(u) {
  const ppm = bell(u.ppm, 300, 520, 150, 900);
  const area = bell(u.area, 58, 85, 45, 130);
  const rooms = u.rooms == null ? 0.5 : bell(u.rooms, 2, 3, 1, 6);
  let floor = 0.5;
  if (u.floor && u.floors) floor = (u.floor === 1 || u.floor === u.floors) ? 0.25 : 1;
  else if (u.floor) floor = u.floor === 1 ? 0.25 : 0.8;
  const ready = (SEMI[u.semi] || SEMI.unfin).w;
  const near = down(u.km, 0, 12);
  const bonus = (u.noCommission ? 0.02 : 0);
  return scale((ppm + area + (rooms + floor) / 2 + ready) / 6 + near / 3 + bonus);
}

