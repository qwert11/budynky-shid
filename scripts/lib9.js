const R = 6371;
const hav = (a1, o1, a2, o2) => {
  const dLat = (a2 - a1) * Math.PI / 180, dLon = (o2 - o1) * Math.PI / 180;
  const s = Math.sin(dLat / 2) ** 2 + Math.cos(a1 * Math.PI / 180) * Math.cos(a2 * Math.PI / 180) * Math.sin(dLon / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(s));
};
function nearestCity(lat, lon) {
  let best = null;
  for (const [n, la, lo, pop] of CITIES9) {
    const d = hav(lat, lon, la, lo);
    const w = d - Math.min(12, Math.sqrt(pop) * 0.55);
    if (!best || w < best.w) best = { city: n.replace(/ \((Хм|Київ|Кір)\)/, ''), km: Math.round(d), w };
  }
  return best || { city: null, km: null };
}

const clamp = (v, a, b) => Math.max(a, Math.min(b, v));
const bell = (v, lo, hi, tailLo, tailHi) => {
  if (v == null) return 0.5;
  if (v >= lo && v <= hi) return 1;
  if (v < lo) return clamp((v - tailLo) / (lo - tailLo), 0, 1);
  return clamp((tailHi - v) / (tailHi - hi), 0, 1);
};
const up = (v, lo, hi) => v == null ? 0.5 : clamp((v - lo) / (hi - lo), 0, 1);
const down = (v, lo, hi) => v == null ? 0.5 : clamp((hi - v) / (hi - lo), 0, 1);
const scale = x => Math.round(42 + 55 * clamp(x, 0, 1));

