// Класс «что готово» по тексту объявления (title + desc) и параметру «Ремонт» OLX.
// null — объявление не про получистовую: либо доводить нечего, либо голая коробка без сетей.
function semiClass(u) {
  const txt = (u.title || '') + '\n' + (u.desc || '');
  const rep = u.repair || '';
  if (/аварійн/i.test(rep)) return null;
  const T = SEMI_TXT;
  const paramShell = /Після будівельників|Під чистову/i.test(rep);
  const shell = paramShell || T.shellStrong.test(txt);
  const needs = T.repairNeed.test(txt) || /Потрібен ремонт|Без ремонту/i.test(rep);
  if (!shell && !needs) return null;
  const livable = T.livable.test(txt) || /Житловий стан|Косметичний ремонт/i.test(rep);
  const isHouse = u.kind !== 'flat';
  if (T.floorUp.test(txt) && (livable || !shell)) return 'floor';
  if (T.part.test(txt)) return 'part';
  if (isHouse && T.mainUnfin.test(txt) && T.annexLiv.test(txt)) return 'annex';
  if (shell) {
    if (isHouse && !T.util.test(txt)) return null;
    return livable ? 'unfin' : 'shell';
  }
  if (T.whileLive.test(txt)) return 'while';
  return 'repair';
}
