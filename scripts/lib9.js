// точка в полигоне (луч по чётности), polys — [[ [lon,lat], … ], …]
function inPolys(lat, lon, polys) {
  let inside = false;
  for (const r of polys) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i], [xj, yj] = r[j];
      if ((yi > lat) !== (yj > lat) && lon < (xj - xi) * (lat - yi) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}
function oblastOf(lat, lon, shapes) {
  if (lat == null || lon == null) return null;
  for (const o of shapes) if (o.geo && inPolys(lat, lon, o.geo)) return o.slug;
  // не попал ни в один упрощённый контур — ближайшая область по подписи не годится, вернём null
  return null;
}

